async function seedMoreProducts() {
  try {
    console.log('[Product Extender] Connecting to database...');
    await sequelize.authenticate();
    console.log('[Product Extender] Authenticated successfully.');

    const categories = await Category.findAll();
    const catMap = {};
    categories.forEach(c => {
      catMap[c.slug] = c.id;
    });

    console.log('[Product Extender] Found categories:', Object.keys(catMap));

    let createdCount = 0;
    for (const item of newProducts) {
      const catId = catMap[item.categorySlug] || catMap['electronics'] || 1;
      
      const existing = await Product.findOne({ where: { sku: item.sku } });
      if (!existing) {
        await Product.create({
          name: item.name,
          slug: item.slug,
          sku: item.sku,
          description: item.description,
          category_id: catId,
          brand: item.brand,
          price: item.price,
          comparePrice: item.comparePrice,
          costPrice: item.costPrice,
          discount: item.discount,
          stock: item.stock,
          lowStockThreshold: item.lowStockThreshold,
          mainImage: item.mainImage,
          images: item.images,
          colors: item.colors,
          rating: item.rating,
          reviewCount: item.reviewCount,
          shippingInfo: ['Regular', 'Economic', 'Next Day', 'Instant'].includes(item.shippingInfo) ? item.shippingInfo : 'Next Day',
          shippingClass: item.shippingClass,
          deliveryTime: item.deliveryTime,
          location: item.location,
          isFeatured: item.isFeatured,
          isNewArrival: item.isNewArrival,
          isOnSale: item.isOnSale,
          specifications: item.specifications,
          features: item.features,
          tags: item.tags
        });
        createdCount++;
        console.log(`[Product Extender] + Created: ${item.name}`);
      } else {
        console.log(`[Product Extender] = Exists: ${item.name}`);
      }
    }

    const totalCount = await Product.count();
    console.log(`[Product Extender] SUCCESS! Added ${createdCount} products. Total products in catalog: ${totalCount}`);
    process.exit(0);
  } catch (err) {
    console.error('[Product Extender] ERROR:', err);
    process.exit(1);
  }
}

seedMoreProducts();
